"""Read-only macro tax-efficiency observer: one LLM call, one proposal, never a trade.

Explicitly NOT a trading engine, NOT market data, NOT a "high-conviction" signal generator.
It reads only the owner's own pasted portfolio description and proposes exactly one
*structural* UK ISA/pension allowance observation - not asset selection, not timing, not a
buy/sell amount tied to live prices. No real money moves; nothing here is capable of moving any.

Does not use kernel.facts.assert_signed_fact(): that function requires the OWNER's own private
signing key, supplied by whatever process already holds it on the owner's own machine - this
server-side module has no such key and will not fabricate one. The proposal is recorded as a
plain Ledger decision event instead (same pattern as twitter_draft_reply/dating_draft_reply:
"saved for your review", never a signed financial fact asserted on the owner's behalf).
"""
from __future__ import annotations

import time

DISCLAIMER = ("This is a structural ISA/pension allowance observation only, generated by a "
              "language model from the text you pasted - it is NOT regulated financial or tax "
              "advice, NOT a trade, NOT asset selection, and nothing here can move any money. "
              "Verify independently (or with a qualified adviser) before acting on it.")

SYSTEM_PROMPT = (
    "You analyze a UK resident's pasted portfolio/savings description for structural tax "
    "efficiency only - ISA allowance usage, pension annual allowance usage, obvious unused "
    "allowance. Propose EXACTLY ONE macro-level structural action (e.g. 'Move up to £X into a "
    "Stocks & Shares ISA' or 'Increase pension contribution by £Y to use more of the annual "
    "allowance'). Never recommend a specific stock, fund, cryptocurrency or timing decision. "
    "Reply in exactly two lines: 'Action: ...' then 'Reasoning: ...' - nothing else."
)

MAX_PORTFOLIO_CHARS = 2000


class WealthEngineError(ValueError):
    pass


def propose_action(budget, ledger, portfolio_text: str, call_anthropic=None, load_api_key=None) -> dict:
    """One budget-gated LLM call. Returns {"action": str, "reasoning": str, "disclaimer": str}.
    Records the proposal as a plain decision event - a claim for the owner to review, not an
    executed or signed financial fact."""
    if not isinstance(portfolio_text, str) or not portfolio_text.strip():
        raise WealthEngineError("Portfolio text is empty")
    portfolio_text = portfolio_text.strip()[:MAX_PORTFOLIO_CHARS]

    if call_anthropic is None or load_api_key is None:
        from apex.agents_research import call_anthropic as _call, load_api_key as _load
        call_anthropic, load_api_key = call_anthropic or _call, load_api_key or _load

    key = f"wealth.{int(time.time() * 1000)}"
    budget.reserve(key, "core", "anthropic", "wealth-analysis-step", 1)
    try:
        api_key = load_api_key()
        reply = call_anthropic(api_key, SYSTEM_PROMPT, portfolio_text, max_tokens=150)
    except Exception:
        budget.release(key)
        raise
    budget.settle(key, 1)

    action, reasoning = "", ""
    for line in reply.splitlines():
        if line.lower().startswith("action:"):
            action = line.split(":", 1)[1].strip()
        elif line.lower().startswith("reasoning:"):
            reasoning = line.split(":", 1)[1].strip()
    if not action:
        action, reasoning = reply.strip(), reasoning  # malformed reply: show it raw rather than hide it

    result = {"action": action, "reasoning": reasoning, "disclaimer": DISCLAIMER}
    if ledger is not None:
        ledger._append(f"wealth-proposal-{key}", "decision", "personal",
                        {"phase": "PROPOSED_NOT_APPROVED", **result})
    return result
